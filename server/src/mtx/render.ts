import { stringify } from 'yaml';
import { availableStreams, playPath, sourcePath, type Model } from '@ugv/shared';

export interface RenderOptions {
  apiPort: number;
  rtspPort: number;
  webrtcPort: number;
  webrtcUdpPort: number;
  /** quoted executable token, see ffmpeg.ts */
  ffmpeg: string;
}

const ON_DEMAND = {
  sourceOnDemand: true, // pull over Starlink only while someone watches
  sourceOnDemandStartTimeout: '15s',
  sourceOnDemandCloseAfter: '10s', // short: stream switching releases the old one quickly
};

/** H.265 -> H.264 baseline, no B-frames, ~1 s GOP at 25 fps. */
function transcodeCmd(ffmpeg: string, srcPath: string): string {
  return [
    ffmpeg,
    '-hide_banner -loglevel error',
    `-rtsp_transport tcp -i rtsp://127.0.0.1:$RTSP_PORT/${srcPath}`,
    '-an -c:v libx264 -preset ultrafast -tune zerolatency -profile:v baseline -bf 0 -g 25',
    '-f rtsp rtsp://127.0.0.1:$RTSP_PORT/$MTX_PATH',
  ].join(' ');
}

/**
 * Full mediamtx.yml for the active model (or no paths when none is selected).
 * Server-level settings mirror the config already proven on the operator laptops.
 * Note: sourceOnDemand must be per path — MediaMTX rejects it on publisher paths.
 */
export function renderMediamtxConfig(model: Model | null, o: RenderOptions): string {
  const paths: Record<string, Record<string, unknown>> = {};

  for (const cam of model?.cameras ?? []) {
    for (const kind of availableStreams(cam)) {
      const url = cam.streams[kind]!;
      const play = playPath(cam.id, kind);
      if (cam.transcode) {
        const src = sourcePath(cam.id, kind);
        paths[src] = { source: url, ...ON_DEMAND };
        paths[play] = {
          runOnDemand: transcodeCmd(o.ffmpeg, src),
          runOnDemandRestart: true,
          runOnDemandStartTimeout: '20s',
          runOnDemandCloseAfter: '10s',
        };
      } else {
        paths[play] = { source: url, ...ON_DEMAND };
      }
    }
  }

  const conf = {
    logLevel: 'info',
    logDestinations: ['stdout'],
    readTimeout: '10s',
    writeTimeout: '10s',
    // Per-reader packet queue (power of two). After a Starlink stall the camera's backlog arrives as
    // one burst; a short queue overflows and drops packets -> smeared picture until the next I-frame.
    // It only fills while a reader is behind, so a bigger one adds no latency in normal operation.
    writeQueueSize: 4096,

    api: true,
    apiAddress: `127.0.0.1:${o.apiPort}`,

    rtsp: true, // local re-stream for QGC
    rtspAddress: `:${o.rtspPort}`,
    rtmp: false,
    hls: false,
    srt: false,
    moq: false, // on by default since MediaMTX 1.17: extra ports + self-signed cert, unused here

    webrtc: true,
    webrtcAddress: `:${o.webrtcPort}`,
    webrtcLocalUDPAddress: `:${o.webrtcUdpPort}`,
    webrtcLocalTCPAddress: '',
    webrtcIPsFromInterfaces: true,
    webrtcICEServers2: [],

    pathDefaults: {
      rtspTransport: 'tcp',
    },
    paths,
  };

  const header = [
    '# GENERATED by ugv-cams — do not edit, changes are overwritten.',
    `# Model: ${model ? `${model.name} (${model.id})` : '<none selected>'}`,
    '',
  ].join('\n');

  return header + stringify(conf, { lineWidth: 0 });
}
